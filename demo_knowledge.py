    """Return the highest scoring curated entry, or None below its threshold."""
    folded = text.casefold()
    best = None
    for entry in KNOWLEDGE:
        score = sum(weight for keyword, weight in entry["keywords"].items() if keyword.casefold() in folded)
        score += sum(4 for pattern in entry.get("patterns", ()) if re.search(pattern, folded))
        if score >= entry.get("threshold", 4) and (best is None or score > best[0]):
            best = (score, entry)
    return best[1] if best else None
